#string methods
x=input("enter the sting:")
print(f"this is captilize method:{x.capitalize()}")
print(f"this is lower method:{x.lower()}")
print(f"this is upper method:{x.upper()}")
print(f"this is title method:{x.title()}")
print(f"this is find method and element is found at index:{x.find(input('enter the element of string to be found:'))}")
print(f"this is count method:{x.count(input('enter the element of string which count should be known:'))}")
print(f"this is replace method and the string that is replaced is:{x.replace(input('enter the part of old string that is to be replaced:'),input('enter the new string that replaces the old string:'))}") 
print(f"this is index method:{x.index(input('enter the element of string which index should be known:'))}")
print(f"this is title method:{x.title()}")
print(f"this is split method:{x.split(input('enter the element of string where it should be splitted:'))}")
print(f"this is islower method:{x.islower()}")
print(f"this is isupper method:{x.isupper()}")
print(f"this is isnumeric method:{x.isnumeric()}")
print(f"this is isalpha method:{x.isalpha()}")
print(f"this is isalnum method:{x.isalnum()}")