# assignment operators  
a = 10
b = 20
print("a=10,b=20")
print(f"(=) is assignment operator and the value of a is: {a}")
a += b
print(f"(+=) is addition assignment operator and the value of a is: {a}")
a -= b
print(f"(-=) is subtraction assignment operator and the value of a is: {a}")
a *= b
print(f"(*=) is multiplication assignment operator and the value of a is: {a}")
a /= b
print(f"(/=) is division assignment operator and the value of a is: {a}")
a %= b
print(f"(%=) is modulus assignment operator and the value of a is: {a}")
a **= b
print(f"(**=) is power assignment operator and the value of a is: {a}")
a //= b
print(f"(//=) is floor division assignment operator and the value of a is: {a}")